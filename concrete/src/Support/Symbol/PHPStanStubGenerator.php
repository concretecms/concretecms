<?php

declare(strict_types=1);

namespace Concrete\Core\Support\Symbol;

use Concrete\Core\Permission\Checker;
use Concrete\Core\Support\Symbol\CheckerGenerator\Method;
use Concrete\Core\Support\Symbol\ClassSymbol\ClassSymbol;

defined('C5_EXECUTE') or die('Access Denied.');

/**
 * Generate a stub file for PHPStan, describing (with @method annotations) the methods that are handled with __call/__callStatic:
 * - the facades
 * - the Permission\Checker class
 */
final class PHPStanStubGenerator
{
    /**
     * @var \Concrete\Core\Support\Symbol\SymbolGenerator
     */
    private $symbolGenerator;

    /**
     * @var \Concrete\Core\Support\Symbol\PhpDocTypeResolver
     */
    private $typeResolver;

    public function __construct(SymbolGenerator $symbolGenerator, PhpDocTypeResolver $typeResolver)
    {
        $this->symbolGenerator = $symbolGenerator;
        $this->typeResolver = $typeResolver;
    }

    public function render(string $eol = "\n", string $padding = '    '): string
    {
        $classes = [];
        foreach ($this->symbolGenerator->getFacades() as $facade) {
            $classes[$facade->getFacadeReflectionClass()->getName()] = $this->renderFacadeLines($facade, $padding);
        }
        $classes[Checker::class] = $this->renderCheckerLines($padding);
        $classes += $this->renderReferencedClassesLines($classes, $padding);
        $namespaces = [];
        foreach ($classes as $fqn => $classLines) {
            $p = strrpos($fqn, '\\');
            $namespace = $p === false ? '' : substr($fqn, 0, $p);
            $namespaces[$namespace][$fqn] = $classLines;
        }
        ksort($namespaces, SORT_STRING);
        $lines = [
            '<?php',
            '',
            '// Generated by the c5:ide-symbols CLI command on ' . date('c'),
            '// This is a stub file for PHPStan: it describes the methods handled by __call/__callStatic with @method annotations.',
        ];
        foreach ($namespaces as $namespace => $namespaceClasses) {
            ksort($namespaceClasses, SORT_STRING);
            $lines[] = '';
            $lines[] = rtrim("namespace {$namespace}");
            $lines[] = '{';
            $first = true;
            foreach ($namespaceClasses as $classLines) {
                if ($first) {
                    $first = false;
                } else {
                    $lines[] = '';
                }
                foreach ($classLines as $line) {
                    $lines[] = rtrim("{$padding}{$line}");
                }
            }
            $lines[] = '}';
        }
        $lines[] = '';

        return implode($eol, $lines);
    }

    /**
     * @return string[]
     */
    private function renderFacadeLines(ClassSymbol $facade, string $padding): array
    {
        $facadeClass = $facade->getFacadeReflectionClass();
        $rootClass = $facade->getReflectionClass();
        $annotations = [];
        foreach ($rootClass->getMethods(\ReflectionMethod::IS_PUBLIC) as $method) {
            $name = $method->getName();
            if (strpos($name, '__') === 0 || isset($annotations[$name]) || $facadeClass->hasMethod($name)) {
                continue;
            }
            $annotations[$name] = '@method static ' . $this->renderMethodSignature($method);
        }
        ksort($annotations, SORT_NATURAL | SORT_FLAG_CASE);

        return $this->renderClassLines(
            $facadeClass,
            "Facade forwarding the static calls to an instance of \\{$rootClass->getName()}",
            $annotations,
            $padding
        );
    }

    /**
     * @return string[]
     */
    private function renderCheckerLines(string $padding): array
    {
        $annotations = [];
        foreach ($this->symbolGenerator->getCheckerGenerator()->getMethods() as $method) {
            $annotations[] = '@method ' . $this->renderCheckerMethodSignature($method);
        }

        return $this->renderClassLines(
            new \ReflectionClass(Checker::class),
            'The methods correspond to the permission keys and to the methods of the permission response classes',
            $annotations,
            $padding
        );
    }

    /**
     * @param string[] $annotations
     *
     * @return string[]
     */
    private function renderClassLines(\ReflectionClass $class, string $description, array $annotations, string $padding): array
    {
        $lines = [
            '/**',
            " * {$description}.",
        ];
        if ($annotations !== []) {
            $lines[] = ' *';
            foreach ($annotations as $annotation) {
                $lines[] = " * {$annotation}";
            }
        }
        $lines[] = ' */';
        if ($class->isInterface()) {
            $kind = 'interface';
        } elseif ($class->isTrait()) {
            $kind = 'trait';
        } else {
            $kind = 'class';
        }
        $lines[] = "{$kind} {$class->getShortName()}";
        $lines[] = '{';
        $lines[] = '}';

        return $lines;
    }

    /**
     * PHPStan validates the stub files in isolation: the classes referenced in the annotations must be declared in the stub file too.
     *
     * @param array<string, string[]> $classes array keys are the fully-qualified class names, array values are the lines already rendered
     *
     * @return array<string, string[]> array keys are the fully-qualified class names, array values are the lines
     */
    private function renderReferencedClassesLines(array $classes, string $padding): array
    {
        $result = [];
        $matches = null;
        foreach ($classes as $classLines) {
            foreach ($classLines as $line) {
                if (strpos($line, '@method') === false || !preg_match_all('/\\\\([A-Za-z_][A-Za-z0-9_\\\\]*)/', $line, $matches)) {
                    continue;
                }
                foreach ($matches[1] as $fqn) {
                    if (isset($classes[$fqn]) || isset($result[$fqn])) {
                        continue;
                    }
                    try {
                        $class = new \ReflectionClass($fqn);
                    } catch (\Throwable $_) {
                        continue;
                    }
                    if ($class->isInternal() || isset($classes[$class->getName()]) || isset($result[$class->getName()])) {
                        continue;
                    }
                    $result[$class->getName()] = $this->renderClassLines(
                        $class,
                        'Empty declaration: it exists because PHPStan validates the stub files in isolation',
                        [],
                        $padding
                    );
                }
            }
        }

        return $result;
    }

    private function renderMethodSignature(\ReflectionMethod $method): string
    {
        $returnType = $this->typeResolver->resolveReturnType($method);
        if ($returnType === '') {
            $returnType = 'mixed';
        }
        $parameters = [];
        foreach ($method->getParameters() as $parameter) {
            $parameters[] = $this->renderParameter($parameter);
        }

        return "{$returnType} {$method->getName()}(" . implode(', ', $parameters) . ')';
    }

    private function renderParameter(\ReflectionParameter $parameter): string
    {
        $result = $this->typeResolver->resolveParameterType($parameter);
        if ($result !== '') {
            $result .= ' ';
        }
        if ($parameter->isPassedByReference()) {
            $result .= '&';
        }
        if ($parameter->isVariadic()) {
            $result .= '...';
        }
        $result .= '$' . $parameter->getName();
        if ($parameter->isDefaultValueAvailable()) {
            $result .= ' = ' . $this->renderDefaultValue($parameter);
        }

        return $result;
    }

    private function renderDefaultValue(\ReflectionParameter $parameter): string
    {
        try {
            // We use the actual values also for constants, so that the stub file doesn't depend on them
            $value = $parameter->getDefaultValue();
        } catch (\Throwable $_) {
            return 'null';
        }
        if (is_array($value)) {
            return $value === [] ? '[]' : str_replace(["\r", "\n"], '', var_export($value, true));
        }
        if ($value === null) {
            return 'null';
        }
        if (is_scalar($value)) {
            return var_export($value, true);
        }

        return 'null';
    }

    private function renderCheckerMethodSignature(Method $method): string
    {
        // Prefix the class names with a backslash, since the arguments are rendered without the leading backslash
        $arguments = preg_replace('/(^|,\s*)([A-Z][A-Za-z0-9_\\\\]*)(\s)/', '$1\\\\$2$3', $method->getArguments());
        if ($arguments === '' && $method->getSees() === []) {
            // Methods corresponding to permission keys: the arguments are forwarded to the permission key validation
            $arguments = 'mixed ...$args';
        }
        $returnType = $method->getReturnType();
        if ($returnType === '') {
            $returnType = 'mixed';
        }

        return "{$returnType} {$method->getName()}({$arguments})";
    }
}
